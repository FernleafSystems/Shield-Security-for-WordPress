use FernleafSystems\Wordpress\Plugin\Shield\Tests\Unit\BaseUnitTest;

class AssetFileRulesTest extends BaseUnitTest {

	private const BUILD = '{"buildDate":1792016945,"buildMeta":{"buildAuthor":"@cklosowski","fileCount":5623,"fileChecksum":"22e7a10707420c21b3802eb4b8a2ecee","manifestChecksum":"%s"}}';

	public function test_edd_build_manifest_downloads_of_one_build_empty_to_the_same_content() :void {
		// Two downloads of EDD Pro 3.7.2 with the same licence: one by the WP Hashes API, one by a site's updater.
		$api = \sprintf( self::BUILD, '14771e1a-6c34-43nM72YBhyPIs3jtZugiQY4siKSziB2Mf0ZKzTLe3VSJcR7SxbcfA6OdN+jhbpmG8rYZ8TgwIxiLCY0LVGZ3iSITLp7A6l4DrYfJUXD33LBRr+pl4rmLdt6Yj8JFGrwI2PLczANqosWfljEmkkv15ik1OchMARpDGCkB55rC7yMPjMU+kU78aqobvicp5PslJI6WDOcCG2FjqgeeUNHS43jwM2YGesuI56z6+vymanF0o=' );
		$site = \sprintf( self::BUILD, '1900a92e-567d-40O0TYMeyeHsToMThKjy3wdXBsL4oaiek73sSa\/d4zW1yR+1DEI63IG\/1nVmOWzm1STHscjx4CFDzlBbq95aKeHhUvMbKIBFMdoKZen0zo6gflQC4bxE4XSnyU9mkT5K0JGPm31wCHlv+E7tMsXOl4pNCmN34hCsz2ERSATtdD98y0VEfUVOdUpVxHQkhpG9tZisHxBXVXNg2yI8G\/gCFtH52zg9ohvrE1jRBw5gpf+P0v45hZbZfGbh2hdfapULeUHor+8p7CeHU4N\/2Yd+5ZDw==' );
		$rules = new AssetFileRules();

		$this->assertSame( \sprintf( self::BUILD, '' ), $rules->apply( 'vendor/build.json', $api ) );
		$this->assertSame( \sprintf( self::BUILD, '' ), $rules->apply( 'vendor/build.json', $site ) );
		$this->assertNull( $rules->apply( 'build.json', $site ) );
		$this->assertNull( $rules->apply( 'lib/vendor/build.json', $site ) );
	}

	public function test_buddyboss_platform_editions_empty_to_the_same_loader() :void {
		// bp-loader.php line 22 in the BuddyBoss Platform 3.6.2 release assets, which differ in nothing else.
		$loader = "<?php\ndefine('BP_PLATFORM_VERSION', '3.6.2');\ndefine('PLATFORM_EDITION', '%s');\n";
		$rules = new AssetFileRules();

		foreach ( [ 'bb-platform', 'bb-platform-free', 'bb-platform-pro-1-site', 'bb-lifetime-deal-10-sites' ] as $edition ) {
			$this->assertSame( \sprintf( $loader, '' ), $rules->apply( 'bp-loader.php', \sprintf( $loader, $edition ) ) );
		}
		$this->assertNull( $rules->apply( 'bp-loader.php', \sprintf( $loader, '' ) ) );
		$this->assertNull( $rules->apply( 'bp-loader.php', \sprintf( $loader, 'bb-platform' ).\sprintf( $loader, 'bb-web' ) ) );
		$this->assertNull( $rules->apply( 'includes/bp-loader.php', \sprintf( $loader, 'bb-platform' ) ) );
	}

	public function test_wp_rocket_licence_data_of_different_customers_empties_to_the_same_file() :void {
		// licence-data.php as every WP Rocket 3.20 to 3.24.1 download writes it: no space before the key's closing parenthesis.
		$licence = "<?php\ndefined( 'ABSPATH' ) || exit;\n\n/**\n * You can edit this file, but it will be overwritten in the next update,\n"
				   ." * it's an autogenerated file, depending on your account\n * or you can define these values directly in your wp-config.php file\n\n */\n\n"
				   ."// Your license KEY.\nif ( ! defined( 'WP_ROCKET_KEY' ) ) {\n\tdefine( 'WP_ROCKET_KEY', '%s');\n}\n\n"
				   ."// Your email, the one you used for the purchase.\nif ( ! defined( 'WP_ROCKET_EMAIL' ) ) {\n\tdefine( 'WP_ROCKET_EMAIL', '%s' );\n}\n";
		$rules = new AssetFileRules();

		foreach ( [ [ '0a1b2c3d', 'owner@example.com' ], [ 'f00dcafe', 'o\\\'brien@example.org' ], [ '', '' ] ] as [ $key, $email ] ) {
			$this->assertSame( \sprintf( $licence, '', '' ), $rules->apply( 'licence-data.php', \sprintf( $licence, $key, $email ) ) );
		}
		$filled = \sprintf( $licence, '0a1b2c3d', 'owner@example.com' );
		$this->assertNull( $rules->apply( 'inc/licence-data.php', $filled ) );
		$this->assertNull( $rules->apply( 'licence-data.php', \strstr( $filled, '// Your email', true ) ) );
		$this->assertNull( $rules->apply( 'licence-data.php', $filled.$filled ) );
		$this->assertNull( $rules->apply( 'licence-data.php', \str_replace( "'0a1b2c3d'", '"0a1b2c3d"', $filled ) ) );
		$this->assertNull( $rules->apply( 'licence-data.php', "define( 'WP_ROCKET_EMAIL', 'owner@example.com' );\ndefine( 'WP_ROCKET_KEY', '0a1b2c3d');\n" ) );
		// Any other definition of either, even in a comment, could pair with the real one and keep its value unverified.
		$this->assertNull( $rules->apply( 'licence-data.php', "<?php\n// define( 'WP_ROCKET_KEY', 'example');\n".\substr( $filled, 6 ) ) );
		$this->assertNull( $rules->apply( 'licence-data.php', \str_replace( '// Your email', "// define( 'WP_ROCKET_EMAIL', 'example' );\n// Your email", $filled ) ) );
		$this->assertNull( $rules->apply( 'licence-data.php', $filled."define('WP_ROCKET_KEY','0a1b2c3d');\n" ) );
		$this->assertNull( $rules->apply( 'licence-data.php', \str_replace( "'0a1b2c3d'", "'0a1b'.'2c3d'", $filled ) ) );
		$this->assertNull( $rules->apply( 'licence-data.php', $filled.'define( "WP_ROCKET_KEY", \'0a1b2c3d\' );'."\n" ) );
		$this->assertNull( $rules->apply( 'licence-data.php', $filled."const WP_ROCKET_EMAIL = 'owner@example.com';\n" ) );
	}

	/**
	 * @dataProvider provideUnrecognisedContent
	 */
	public function test_content_without_exactly_one_recognised_value_is_left_as_is( string $content ) :void {
		$this->assertNull( ( new AssetFileRules() )->apply( 'vendor/build.json', $content ) );
	}

	public function provideUnrecognisedContent() :array {
		return [
			'already empty'   => [ \sprintf( self::BUILD, '' ) ],
			'no UUID prefix'  => [ \sprintf( self::BUILD, 'O0TYMeyeHsToMThKjy3wdXBsL4oaiek73sSa' ) ],
			'unescaped slash' => [ \sprintf( self::BUILD, '1900a92e-567d-40O0TY/Mey' ) ],
			'twice'           => [ \sprintf( self::BUILD, '1900a92e-567d-40O0TYMey' ).\sprintf( self::BUILD, '1900a92e-567d-40O0TYMey' ) ],
			'spaced'          => [ '{"manifestChecksum": "1900a92e-567d-40O0TYMey"}' ],
		];
	}
}
