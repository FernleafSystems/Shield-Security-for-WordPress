<?php declare( strict_types=1 );

namespace FernleafSystems\Wordpress\Plugin\Shield\VirtualPatching\EarlyLoading;

/**
 * Builds the stub that auto_prepend_file points at. The stub lives outside the plugin so that
 * removing the plugin never leaves PHP requiring a missing file, and it only includes files that
 * exist. It must parse on any PHP version a site might switch to, so it uses PHP 5 syntax only;
 * the bootstrap is included only on PHP 7.4 or later.
 */
final class StubBuilder {

	public const FILE_NAME = 'shield-early-loader.php';

	/**
	 * The stub's first comment line, by which Shield recognises its own stub.
	 */
	public const HEADER = '// Generated by Shield Security to run its protection before WordPress. Do not edit.';

	/**
	 * Printed only when the stub itself is requested, so an install can check the web server runs it.
	 */
	public const SMOKE_MARKER = 'shield-early-loader-ok';

	/**
	 * @param array $scope which PHP files the early pass covers, see EarlyPass::coversScript()
	 */
	public static function build( string $bootstrapPath, string $rulesetPath, ?string $hostPrependPath, array $scope ) :string {
		// A host can disable any PHP function, and this runs on every request, so each one is checked first.
		// SHIELD_EARLY_LOADED holds this file's path so Shield can tell its own stub from another site's.
		$lines = [
			'<?php',
			self::HEADER,
			'// Remove any auto_prepend_file setting that points to this file before deleting it.',
			"if (!defined('SHIELD_EARLY_LOADED')) {",
			"\tdefine('SHIELD_EARLY_LOADED', __FILE__);",
		];

		if ( $hostPrependPath !== null ) {
			$host = \var_export( $hostPrependPath, true );
			\array_push( $lines,
				"\t// The auto_prepend_file configured before Shield's early loader was installed.",
				sprintf( "\tif (function_exists('is_file') && is_file(%s)) {", $host ),
				sprintf( "\t\tinclude_once %s;", $host ),
				"\t}"
			);
		}

		$bootstrap = \var_export( $bootstrapPath, true );
		\array_push( $lines,
			sprintf( "\tif (PHP_VERSION_ID >= 70400 && function_exists('is_file') && is_file(%s)) {", $bootstrap ),
			sprintf( "\t\tdefine('SHIELD_EARLY_RULESET', %s);", \var_export( $rulesetPath, true ) ),
			sprintf( "\t\tdefine('SHIELD_EARLY_SCOPE', %s);", \preg_replace( "#\s*\n\s*#", ' ', \var_export( $scope, true ) ) ),
			// A plugin update can leave the bootstrap half written for a moment.
			"\t\ttry {",
			sprintf( "\t\t\tinclude_once %s;", $bootstrap ),
			"\t\t}",
			"\t\tcatch (Throwable \$shieldEarlyLoaderError) {",
			"\t\t\tunset(\$shieldEarlyLoaderError);",
			"\t\t}",
			"\t}",
			'}',
			"if (isset(\$_SERVER['SCRIPT_FILENAME']) && function_exists('realpath') && realpath(\$_SERVER['SCRIPT_FILENAME']) === __FILE__) {",
			sprintf( "\techo %s;", \var_export( self::SMOKE_MARKER, true ) ),
			'}',
			''
		);

		return \implode( "\n", $lines );
	}
}
